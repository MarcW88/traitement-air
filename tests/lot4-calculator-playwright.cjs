const { chromium } = require('@playwright/test');
const path = require('node:path');
(async () => {
 const browser = await chromium.launch({headless:true});
 const page = await browser.newPage({viewport:{width:390,height:844}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve('outils/calcul-renouvellement-air/index.html'));
 await page.locator('#ach-submit').click();
 let output=await page.locator('#ach-output').innerText();
 if(!output.includes('1 200')&&!output.includes('1 200')) throw Error('Default volume incorrect: '+output);
 if(!output.includes('4 800')&&!output.includes('4 800')) throw Error('Default debit incorrect: '+output);
 await page.locator('#ach-l').fill('10');
 await page.locator('#ach-w').fill('5');
 await page.locator('#ach-h').fill('2');
 await page.locator('#ach-n').fill('2.5');
 await page.locator('#ach-submit').click();
 output=await page.locator('#ach-output').innerText();
 if(!output.includes('100')||!output.includes('250')) throw Error('Decimal result incorrect: '+output);
 await page.locator('#ach-l').fill('0');
 await page.locator('#ach-submit').click();
 output=await page.locator('#ach-output').innerText();
 if(!output.includes('strictement positives')) throw Error('Invalid value not rejected: '+output);
 await page.locator('#ach-l').fill('');
 await page.locator('#ach-submit').click();
 output=await page.locator('#ach-output').innerText();
 if(!output.includes('strictement positives')) throw Error('Empty value not rejected: '+output);
 if(errors.length) throw Error('Browser errors: '+errors.join('; '));
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth);
 if(overflow) throw Error('Horizontal overflow at 390px viewport');
 console.log('PLAYWRIGHT PASS: defaults, decimals, zero, empty, browser errors, mobile overflow');
 await browser.close();
})().catch(err=>{console.error(err);process.exit(1)});
